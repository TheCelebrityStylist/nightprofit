export type AuthLocale = keyof typeof authenticatedMessages;
export type AuthMessageKey = keyof typeof authenticatedMessages.nl;

const englishMessages: Record<AuthMessageKey, string> = authenticatedMessages.en;
void englishMessages;

export function normalizeAuthLocale(value: string | null | undefined): AuthLocale {
  return value?.toLowerCase().startsWith("en") ? "en" : "nl";
}

export function authMessage(locale: AuthLocale, key: AuthMessageKey): string {
  return authenticatedMessages[locale][key];
}

export function authIntlLocale(locale: AuthLocale): "nl-NL" | "en-GB" {
  return locale === "nl" ? "nl-NL" : "en-GB";
}
